use std::{
    error::Error,
    fs,
    path::{Path, PathBuf},
};

mod extractor;
#[allow(dead_code)]
mod parser;
mod rust;

fn main() -> Result<(), Box<dyn Error>> {
    let mut arguments = std::env::args().skip(1).collect::<Vec<_>>();
    let fast_math_count = arguments
        .iter()
        .filter(|argument| argument.as_str() == "--fast-math")
        .count();
    if fast_math_count > 1 {
        return Err("--fast-math may only be specified once".into());
    }
    let fast_math = fast_math_count == 1;
    arguments.retain(|argument| argument != "--fast-math");
    let mut args = arguments.into_iter();
    match args.next().as_deref() {
        Some("--tests") if args.next().is_none() => {
            return compile_tests(fast_math);
        }
        Some("--runtime") => {
            let output = args
                .next()
                .ok_or("usage: aida-ast [--fast-math] --runtime <output.rs> <input.sb3>")?;
            let input = args
                .next()
                .ok_or("usage: aida-ast [--fast-math] --runtime <output.rs> <input.sb3>")?;
            if args.next().is_some() {
                return Err(
                    "usage: aida-ast [--fast-math] --runtime <output.rs> <input.sb3>".into(),
                );
            }
            return compile_runtime_module(&input, &output, fast_math);
        }
        Some(argument) => {
            return Err(format!("unknown argument: {argument}\nusage: aida-ast [--fast-math] [--tests] | --runtime <output.rs> <input.sb3>").into());
        }
        None => {
            return Err(
                "usage: aida-ast [--fast-math] [--tests] | --runtime <output.rs> <input.sb3>"
                    .into(),
            );
        }
    }
}

fn compile_runtime_module(
    input: &str,
    output: &str,
    fast_math: bool,
) -> Result<(), Box<dyn Error>> {
    let json = extractor::read_project_json(input)?;
    let project = parser::parse_project(&json)?;
    let output_path = Path::new(output);
    let (list_data_path, list_data_filename) = list_data_path(output_path)?;
    let (generated, list_data) =
        rust::generate_with_list_data(&project, fast_math, &list_data_filename);
    let mode_comment = format!(
        "{}{}",
        if fast_math {
            "// fast math enabled; scratch edge-case compatibility is relaxed.\n"
        } else {
            ""
        },
        ""
    );
    let module = format!(
        "// Generated by aida-ast from {}. Do not edit by hand.\n#![allow(unused_parens)]\n// Scratch expression groups are kept explicit as nested code is emitted.\n{mode_comment}{}",
        Path::new(input).display(),
        generated
    );
    write_optional_file(&list_data_path, list_data.as_deref())?;
    write_if_changed(output_path, module.as_bytes())?;
    let modes = [fast_math.then_some("fast-math")]
        .into_iter()
        .flatten()
        .collect::<Vec<_>>();
    if modes.is_empty() {
        println!("Generated runtime module {output} from {input}");
    } else {
        println!(
            "Generated {} runtime module {output} from {input}",
            modes.join(" and ")
        );
    }
    Ok(())
}

fn write_if_changed(output: &Path, contents: &[u8]) -> Result<(), std::io::Error> {
    match fs::read(output) {
        Ok(existing) if existing == contents => return Ok(()),
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
        Err(error) => return Err(error),
    }
    fs::write(output, contents)
}

fn write_optional_file(path: &Path, contents: Option<&[u8]>) -> Result<(), std::io::Error> {
    if let Some(contents) = contents {
        return write_if_changed(path, contents);
    }
    match fs::remove_file(path) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error),
    }
}

fn list_data_path(output: &Path) -> Result<(PathBuf, String), Box<dyn Error>> {
    let mut filename = output
        .file_name()
        .ok_or("runtime output path must include a filename")?
        .to_os_string();
    filename.push(".lists.json");
    let include_filename = filename.to_string_lossy().into_owned();
    Ok((output.with_file_name(filename), include_filename))
}

fn compile_tests(fast_math: bool) -> Result<(), Box<dyn Error>> {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let source_dir = crate_dir.join("tests/src");
    let output_dir = crate_dir.join("tests/output");
    fs::create_dir_all(&output_dir)?;

    let mut inputs: Vec<PathBuf> = fs::read_dir(source_dir)?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<_, _>>()?;
    inputs.retain(|path| {
        path.is_file()
            && path
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("sb3"))
    });
    inputs.sort();

    for input in &inputs {
        let json = extractor::read_project_json(input)?;
        let project = parser::parse_project(&json)?;
        let output_name = input
            .file_stem()
            .ok_or("test project has no filename")?
            .to_string_lossy();
        let output = output_dir.join(format!("{output_name}.rs"));
        let (list_data_path, list_data_filename) = list_data_path(&output)?;
        let (generated, list_data) =
            rust::generate_with_list_data(&project, fast_math, &list_data_filename);
        write_optional_file(&list_data_path, list_data.as_deref())?;
        fs::write(&output, generated)?;
        println!("Compiled {} -> {}", input.display(), output.display());
    }

    println!("Compiled {} test project(s)", inputs.len());
    Ok(())
}
